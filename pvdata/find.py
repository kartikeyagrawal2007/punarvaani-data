"""Build a sources CSV from YouTube searches, one search per row (runs yt-dlp; needs internet).

Input CSV columns: ``speaker,query``, e.g. ``ravish,Ravish Kumar Official``. For each row we take the
top N search results whose length is within [min_minutes, max_minutes] and write them as sources rows,
with the video title and channel in ``notes`` so you can check them before mining.

A speaker starting with ``@`` (e.g. ``@tedx``) means "a different person in every video" (TEDx, NPTEL,
Josh Talks): each video gets its own speaker id, like ``tedx_<video id>``.

Always review the output: search can return clips of other people, panels or compilations.
Delete those rows before ``pvdata run``.
"""

from __future__ import annotations

import csv
import subprocess
from dataclasses import dataclass
from pathlib import Path

from pvdata.media import _require


@dataclass
class Hit:
    video_id: str
    duration: float
    title: str
    channel: str

    @property
    def url(self) -> str:
        return f"https://www.youtube.com/watch?v={self.video_id}"


def parse_hits(stdout: str) -> list[Hit]:
    hits = []
    for line in stdout.splitlines():
        parts = line.split("\t")
        if len(parts) < 4 or not parts[0]:
            continue
        try:
            dur = float(parts[1])
        except ValueError:
            dur = 0.0
        hits.append(Hit(parts[0], dur, parts[2].strip(), parts[3].strip()))
    return hits


def search(query: str, n: int, min_minutes: float, max_minutes: float, pool: int = 25) -> list[Hit]:
    cmd = [_require("yt-dlp"), "--flat-playlist", "--no-warnings", "--print",
           "%(id)s\t%(duration)s\t%(title)s\t%(channel)s", f"ytsearch{pool}:{query}"]  # fmt: skip
    out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    ok = [h for h in parse_hits(out) if min_minutes * 60 <= h.duration <= max_minutes * 60]
    return ok[:n]


def find_sources(queries_csv: str | Path, out_csv: str | Path, per_speaker: int = 3, min_minutes: float = 4,
                 max_minutes: float = 40) -> int:  # fmt: skip
    with open(queries_csv, encoding="utf-8", newline="") as f:
        rows = [r for r in csv.DictReader(line for line in f if not line.lstrip().startswith("#")) if r.get("query")]
    seen: set[str] = set()
    n = 0
    with open(out_csv, "w", encoding="utf-8", newline="") as f:
        f.write(
            "# Generated by `pvdata find`. REVIEW EVERY ROW: keep only videos where this one person talks to the camera.\n"
        )
        w = csv.writer(f)
        w.writerow(["url", "speaker", "start", "end", "notes"])
        for r in rows:
            for h in search(r["query"].strip(), per_speaker, min_minutes, max_minutes):
                if h.video_id in seen:
                    continue
                seen.add(h.video_id)
                speaker = r["speaker"].strip()
                if speaker.startswith("@"):
                    speaker = f"{speaker[1:]}_{h.video_id}"
                w.writerow([h.url, speaker, "", "", f"{h.channel} | {h.title} | {h.duration / 60:.0f} min"])
                n += 1
    return n
